#!/usr/bin/env python3
"""Generate layout/src/layout_table.rs from the XKB Khmer layout (xkeyboard-config symbols/kh, NiDA layout,
original author Jens Herden 2005). Keeps the key table machine-made, not hand-typed.

  python3 layout/tools/gen_layout.py /usr/share/X11/xkb/symbols/kh > layout/src/layout_table.rs
"""
import re, sys

# XKB key name -> (US character without Shift, macOS virtual key code, Windows set-1 scan code)
KEYS = {
 "TLDE": ("`", 50, 0x29), "AE01": ("1", 18, 0x02), "AE02": ("2", 19, 0x03), "AE03": ("3", 20, 0x04),
 "AE04": ("4", 21, 0x05), "AE05": ("5", 23, 0x06), "AE06": ("6", 22, 0x07), "AE07": ("7", 26, 0x08),
 "AE08": ("8", 28, 0x09), "AE09": ("9", 25, 0x0A), "AE10": ("0", 29, 0x0B), "AE11": ("-", 27, 0x0C),
 "AE12": ("=", 24, 0x0D),
 "AD01": ("q", 12, 0x10), "AD02": ("w", 13, 0x11), "AD03": ("e", 14, 0x12), "AD04": ("r", 15, 0x13),
 "AD05": ("t", 17, 0x14), "AD06": ("y", 16, 0x15), "AD07": ("u", 32, 0x16), "AD08": ("i", 34, 0x17),
 "AD09": ("o", 31, 0x18), "AD10": ("p", 35, 0x19), "AD11": ("[", 33, 0x1A), "AD12": ("]", 30, 0x1B),
 "AC01": ("a", 0, 0x1E), "AC02": ("s", 1, 0x1F), "AC03": ("d", 2, 0x20), "AC04": ("f", 3, 0x21),
 "AC05": ("g", 5, 0x22), "AC06": ("h", 4, 0x23), "AC07": ("j", 38, 0x24), "AC08": ("k", 40, 0x25),
 "AC09": ("l", 37, 0x26), "AC10": (";", 41, 0x27), "AC11": ("'", 39, 0x28), "BKSL": ("\\", 42, 0x2B),
 "AB01": ("z", 6, 0x2C), "AB02": ("x", 7, 0x2D), "AB03": ("c", 8, 0x2E), "AB04": ("v", 9, 0x2F),
 "AB05": ("b", 11, 0x30), "AB06": ("n", 45, 0x31), "AB07": ("m", 46, 0x32), "AB08": (",", 43, 0x33),
 "AB09": (".", 47, 0x34), "AB10": ("/", 44, 0x35),
}
# US Shift pairs: the character a US keyboard types with Shift -> the key, named by its unshifted character.
# Auto mode reads ASCII that was typed on a US keyboard, so "?" means "the Shift level of the / key".
SHIFTED_US = {"!": "1", "@": "2", "#": "3", "$": "4", "%": "5", "^": "6", "&": "7", "*": "8", "(": "9", ")": "0",
              "_": "-", "+": "=", "~": "`", "{": "[", "}": "]", "|": "\\", ":": ";", '"': "'", "<": ",", ">": ".", "?": "/"}
assert all(b in [k[0] for k in KEYS.values()] for b in SHIFTED_US.values())

NAMED = {"guillemotleft": "«", "guillemotright": "»", "exclam": "!", "at": "@", "quotedbl": '"',
         "dollar": "$", "percent": "%", "EuroSign": "€", "asterisk": "*", "parenleft": "(", "parenright": ")",
         "braceleft": "{", "braceright": "}", "equal": "=", "backslash": "\\", "comma": ",", "period": ".",
         "slash": "/", "question": "?", "space": " ", "nobreakspace": " ", "x": "x"}

def sym(s):
    s = s.strip()
    if s == "none":
        return ""
    m = re.fullmatch(r"U([0-9a-fA-F]{4,6})", s)
    if m:
        return chr(int(m.group(1), 16))
    return NAMED[s]

src = open(sys.argv[1], encoding="utf-8").read()
basic = src[src.index('xkb_symbols "basic"'):src.index('xkb_symbols "olpc"')]
rows = {}
for name, levels in re.findall(r"key\s+<(\w+)>\s*\{\[([^\]]*)\]\}", basic):
    if name in KEYS:
        lv = [sym(x) for x in levels.split(",")]
        lv += [""] * (4 - len(lv))
        rows[name] = lv
missing = sorted(set(KEYS) - set(rows))
assert not missing, missing

def lit(s):
    return '"' + "".join(c if (c.isprintable() and c not in '"\\' and ord(c) < 0x2000) else "\\u{%x}" % ord(c) for c in s) + '"'

print("// @generated by layout/tools/gen_layout.py from the XKB Khmer layout (xkeyboard-config symbols/kh).")
print("// Khmer Unicode standard keyboard layout of NiDA, Cambodia; original XKB author Jens Herden, 2005.")
print("// Columns: US key, macOS virtual key code, Windows set-1 scan code, then the four levels:")
print("// normal, Shift, right Alt (AltGr / Option), Shift + right Alt. An empty string means the level is not mapped.")
print("// Do not edit by hand.")
print("pub const KEYS: [Key; %d] = [" % len(KEYS))
for name, (us, mac, win) in KEYS.items():
    a, b, c, d = rows[name]
    us_l = "'\\\\'" if us == "\\" else ("'\\''" if us == "'" else "'%s'" % us)
    print("    Key { us: %s, mac: %d, win: 0x%02X, levels: [%s, %s, %s, %s] }, // %s" % (us_l, mac, win, lit(a), lit(b), lit(c), lit(d), name))
print("];")

def ch(c):
    return {"\\": "'\\\\'", "'": "'\\''"}.get(c, "'%s'" % c)

print()
print("/// US Shift pairs: (the character a US keyboard types with Shift, the unshifted character of its key).")
print("pub const SHIFTED_US: [(char, char); %d] = [" % len(SHIFTED_US))
for shifted, base in SHIFTED_US.items():
    print("    (%s, %s)," % (ch(shifted), ch(base)))
print("];")
